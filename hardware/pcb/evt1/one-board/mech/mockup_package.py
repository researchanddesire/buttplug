"""Package FreeCAD-derived meshes and installed P2S presets for Bambu Studio.

Run with normal Python. No CAD geometry is generated by this packager.
"""
from pathlib import Path
import json
import struct
import zipfile
import xml.etree.ElementTree as ET

MECH = Path(__file__).resolve().parent
PACKET = MECH / 'print-mockup'
BUILD = MECH.parent / 'build' / 'mockup'
PROFILES = Path('/Applications/BambuStudio.app/Contents/Resources/profiles/BBL')
NS = 'http://schemas.microsoft.com/3dmanufacturing/core/2015/02'
ET.register_namespace('', NS)

def tag(name):
    return '{' + NS + '}' + name

def read_stl(path):
    data = path.read_bytes()
    count = struct.unpack_from('<I', data, 80)[0]
    assert len(data) == 84 + count * 50
    points, triangles, indices = [], [], {}
    for i in range(count):
        values = struct.unpack_from('<12fH', data, 84 + i * 50)
        face = []
        for j in (3, 6, 9):
            xyz = values[j:j+3]
            if xyz not in indices:
                indices[xyz] = len(points)
                points.append(xyz)
            face.append(indices[xyz])
        triangles.append(face)
    return points, triangles

def make_plate():
    model = ET.Element(tag('model'), unit='millimeter')
    ET.SubElement(model, tag('metadata'), name='Title').text = 'Compass inert mockup - P2S 0.4 mm'
    resources = ET.SubElement(model, tag('resources'))
    placements = [('MockupHalfA', 80, 60), ('MockupHalfB', 150, 60),
                  ('MockupAlignmentPin', 94, 190), ('MockupAlignmentPin', 106, 190),
                  ('MockupAlignmentPin', 118, 190)]
    build = ET.SubElement(model, tag('build'))
    for i, (name, x, y) in enumerate(placements, 1):
        points, faces = read_stl(PACKET / (name + '.stl'))
        obj = ET.SubElement(resources, tag('object'), id=str(i), type='model', name=name + (' '+str(i-2) if i>2 else ''))
        mesh = ET.SubElement(obj, tag('mesh'))
        vertices = ET.SubElement(mesh, tag('vertices'))
        for a, b, c in points:
            ET.SubElement(vertices, tag('vertex'), x=f'{a:.8f}', y=f'{b:.8f}', z=f'{c:.8f}')
        triangles = ET.SubElement(mesh, tag('triangles'))
        for a, b, c in faces:
            ET.SubElement(triangles, tag('triangle'), v1=str(a), v2=str(b), v3=str(c))
        ET.SubElement(build, tag('item'), objectid=str(i),
            transform=f'1 0 0 0 1 0 0 0 1 {x} {y} 0')
    with zipfile.ZipFile(BUILD / 'mockup-plate-input.3mf', 'w', zipfile.ZIP_DEFLATED) as archive:
        archive.writestr('3D/3dmodel.model', ET.tostring(model, encoding='utf-8', xml_declaration=True))
        archive.writestr('_rels/.rels', '<?xml version="1.0"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Target="/3D/3dmodel.model" Id="rel0" Type="http://schemas.microsoft.com/3dmanufacturing/2013/01/3dmodel"/></Relationships>')
        archive.writestr('[Content_Types].xml', '<?xml version="1.0"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="model" ContentType="application/vnd.ms-package.3dmanufacturing-3dmodel+xml"/></Types>')

def resolve(kind, name):
    raw = json.loads((PROFILES / kind / (name + '.json')).read_text())
    result = resolve(kind, raw['inherits']) if raw.get('inherits') else {}
    for include in raw.get('include', []):
        result.update(resolve(kind, include))
    result.update(raw)
    for key in ('inherits', 'include'):
        result.pop(key, None)
    return result

make_plate()
machine = resolve('machine', 'Bambu Lab P2S 0.4 nozzle')
machine['printer_settings_id'] = machine['name']
process = resolve('process', '0.16mm High Quality @BBL P2S')
process.update(name='Compass mockup - 0.16mm P2S 0.4',
    print_settings_id='Compass mockup - 0.16mm P2S 0.4',
    layer_height='0.16', initial_layer_print_height='0.2', wall_loops='3',
    top_shell_layers='5', bottom_shell_layers='5', sparse_infill_density='15%',
    sparse_infill_pattern='gyroid', enable_support='0', brim_type='outer_only',
    brim_width='3', brim_object_gap='0.1',
    outer_wall_speed=['60']*3, top_surface_speed=['80']*3,
    inner_wall_speed=['150']*3, sparse_infill_speed=['150']*3)
filament = resolve('filament', 'Generic PLA @BBL P2S')
filament['filament_settings_id'] = [filament['name']]
filament['filament_colour'] = ['#B8BAC2']
for name, value in [('machine', machine), ('process', process), ('filament', filament)]:
    (BUILD / (name + '.json')).write_text(json.dumps(value, indent=2) + '\n')
print('Prepared five objects, exact installed P2S 0.4 mm presets, and 0.16 mm PLA process.')
